export function getKarachiNeighborhoodName(index) {
  const safeIndex = Number.isFinite(index)
    ? Math.min(KARACHI_NEIGHBORHOODS.length, Math.max(1, Math.floor(index)))
    : 1;
  return KARACHI_NEIGHBORHOODS[safeIndex - 1];
}

export function getKarachiNeighborhoodNames() {
  return KARACHI_NEIGHBORHOODS.slice();
}
